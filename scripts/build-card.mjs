// Bundles src/ into the HACS entrypoint van-power-card.js.
// three.js stays external: it is loaded from vendor/shared/ (built by build-vendor.mjs),
// which other cards also import from /local/van_power/vendor/shared/.
import { build, context } from "esbuild";
import { readdir, readFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const vendorAliases = {
  "vendor:three": "./vendor/shared/three-entry.js",
  "vendor:gltf-loader": "./vendor/shared/gltf-loader-entry.js",
};

async function importedNames(alias) {
  const names = new Set();
  const pattern = new RegExp(String.raw`import \{([^}]*)\} from "` + alias + `"`, "g");
  for (const file of await readdir(join(root, "src"), { recursive: true })) {
    if (!file.endsWith(".js")) continue;
    const code = await readFile(join(root, "src", file), "utf8");
    for (const match of code.matchAll(pattern)) {
      for (const name of match[1].split(",")) if (name.trim()) names.add(name.trim().split(/\s+as\s+/)[0]);
    }
  }
  return names;
}

const options = {
  absWorkingDir: root,
  entryPoints: ["src/index.js"],
  outfile: "van-power-card.js",
  bundle: true,
  format: "esm",
  target: "es2020",
  charset: "utf8",
  legalComments: "none",
  banner: { js: "// Generated from src/ by `npm run build`. Do not edit this file directly." },
  plugins: [{
    name: "vendor-externals",
    setup(b) {
      // Route every `vendor:*` import through one virtual module per alias so the
      // bundle ends up with a single import statement per vendor file.
      b.onResolve({ filter: /^vendor:/ }, (args) => {
        if (!vendorAliases[args.path]) throw new Error(`Unknown vendor alias ${args.path}`);
        return { path: args.path, namespace: "vendor" };
      });
      // Re-export only the names src/ actually imports, as named bindings, so the
      // bundle keeps direct ES module bindings (no namespace-object indirection).
      b.onLoad({ filter: /.*/, namespace: "vendor" }, async (args) => {
        const names = await importedNames(args.path);
        return {
          contents: `export { ${[...names].sort().join(", ")} } from ${JSON.stringify(vendorAliases[args.path])};`,
          resolveDir: root,
        };
      });
      b.onResolve({ filter: /^\.\/vendor\/shared\// }, (args) => ({ path: args.path, external: true }));
    },
  }],
};

if (process.argv.includes("--watch")) {
  const ctx = await context(options);
  await ctx.watch();
  console.log("Watching src/ ...");
} else {
  await build(options);
}
